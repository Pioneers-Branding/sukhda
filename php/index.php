function embedded_image(string $relativePath): string
{
    $absolutePath = __DIR__ . '/assets/images/' . ltrim($relativePath, '/');
    if (!is_file($absolutePath))
        return '';
    $mime = function_exists('mime_content_type') ? mime_content_type($absolutePath) : 'image/jpeg';
    return 'data:' . ($mime ?: 'image/jpeg') . ';base64,' . base64_encode((string) file_get_contents($absolutePath));
}
