        (function () {
            const nav = document.querySelector('.nav');
            const button = document.querySelector('.hamb');
            const closeBtn = document.querySelector('.mobile-close-btn');
            const overlay = document.querySelector('.nav-overlay');
            const menu = document.querySelector('.menu');
            if (!nav || !button || !menu) return;

            menu.id = 'mobile-menu';
            button.type = 'button';
            button.setAttribute('aria-controls', menu.id);
            button.setAttribute('aria-expanded', 'false');
            button.setAttribute('aria-label', 'Open menu');

            const close = () => {
                nav.classList.remove('open');
                document.body.style.overflow = '';
                button.setAttribute('aria-expanded', 'false');
                button.setAttribute('aria-label', 'Open menu');
                button.blur();
            };
            const openMenu = () => {
                nav.classList.add('open');
                document.body.style.overflow = 'hidden';
                button.setAttribute('aria-expanded', 'true');
                button.setAttribute('aria-label', 'Close menu');
            };

            button.onclick = e => {
                e.preventDefault();
                e.stopPropagation();
                nav.classList.contains('open') ? close() : openMenu();
            };
            if (closeBtn) closeBtn.onclick = e => { e.preventDefault(); close(); };
            if (overlay) overlay.onclick = e => { e.preventDefault(); close(); };

            const navGroups = menu.querySelectorAll('.nav-group');
            navGroups.forEach(group => {
                const parentLink = group.querySelector(':scope > a');
                if (!parentLink) return;
                parentLink.addEventListener('click', e => {
                    if (window.innerWidth <= 900) {
                        e.preventDefault();
                        e.stopPropagation();
                        const isOpen = group.classList.contains('open');
                        navGroups.forEach(g => { if (g !== group) g.classList.remove('open'); });
                        group.classList.toggle('open', !isOpen);
                    }
                });
            });

            menu.addEventListener('click', e => {
                const a = e.target.closest('a');
                if (!a) return;
                if (a.closest('.nav-drop') || !a.closest('.nav-group')) {
                    close();
                }
            });

            document.addEventListener('keydown', e => { if (e.key === 'Escape') close(); });
        })();

        // Generic Carousel Helper
        function initSlider(trackId, prevId, nextId, cardSelector) {
            const track = document.getElementById(trackId);
            const prev = document.getElementById(prevId);
            const next = document.getElementById(nextId);
            if (!track || !prev || !next) return;

            const updateBtns = () => {
                const max = track.scrollWidth - track.clientWidth;
                prev.disabled = track.scrollLeft <= 5;
                next.disabled = track.scrollLeft >= max - 5;
            };

            const getScrollStep = () => {
                const item = track.querySelector(cardSelector);
                const itemWidth = item ? item.offsetWidth + 14 : 200;
                const visibleCount = Math.max(1, Math.floor(track.clientWidth / itemWidth));
                return Math.max(itemWidth, visibleCount * itemWidth * 0.85);
            };

            prev.addEventListener('click', () => {
                track.scrollBy({ left: -getScrollStep(), behavior: 'smooth' });
            });

            next.addEventListener('click', () => {
                track.scrollBy({ left: getScrollStep(), behavior: 'smooth' });
            });

            track.addEventListener('scroll', updateBtns, { passive: true });
            window.addEventListener('resize', updateBtns);

            let isDown = false, startX, scrollLeft, moved = false;
            track.addEventListener('mousedown', (e) => {
                isDown = true;
                moved = false;
                track.classList.add('is-dragging');
                startX = e.pageX - track.offsetLeft;
                scrollLeft = track.scrollLeft;
            });

            window.addEventListener('mouseup', () => {
                if (!isDown) return;
                isDown = false;
                track.classList.remove('is-dragging');
            });

            track.addEventListener('mouseleave', () => {
                if (!isDown) return;
                isDown = false;
                track.classList.remove('is-dragging');
            });

            track.addEventListener('mousemove', (e) => {
                if (!isDown) return;
                e.preventDefault();
                const x = e.pageX - track.offsetLeft;
                const walk = (x - startX) * 1.4;
                if (Math.abs(walk) > 4) moved = true;
                track.scrollLeft = scrollLeft - walk;
            });

            track.addEventListener('click', (e) => {
                if (moved) {
                    e.preventDefault();
                    e.stopPropagation();
                }
            }, true);

            updateBtns();
        }

        initSlider('servicesTrack', 'servicesPrev', 'servicesNext', '.service');
        initSlider('docsTrack', 'docsPrev', 'docsNext', '.doctor-card');
    </script>
